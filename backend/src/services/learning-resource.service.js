const tokenize = (value) => new Set(String(value || "").toLowerCase().match(/[a-z0-9+#.]{2,}/g) || []);

export const getReadableResourcesForInterview = (interview = {}) => {
    const context = [
        interview.role,
        interview.summary,
        ...(interview.skill_gaps || []),
        ...(interview.topics || []).map((topic) => topic.topic),
    ].join(" ");
    const contextTokens = tokenize(context);
    return RESOURCES
        .map((resource, index) => ({
            resource,
            score: resource.tags.reduce((total, tag) => total + [...tokenize(tag)].filter((token) => contextTokens.has(token)).length, 0),
            index,
        }))
        .sort((left, right) => right.score - left.score || left.index - right.index)
        .map(({ resource }) => resource);
};

