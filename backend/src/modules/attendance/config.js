const HHMM_RE = /^([01]?\d|2[0-3]):([0-5]\d)$/;

/** "9:05" / "09:05" → {hour, minute, minutes, text:"09:05"}; null when invalid. */
export const parseHHmm = (value) => {
    const match = HHMM_RE.exec(String(value ?? "").trim());
    if (!match) return null;
    const hour = Number(match[1]);
    const minute = Number(match[2]);
    return { hour, minute, minutes: hour * 60 + minute, text: `${String(hour).padStart(2, "0")}:${match[2]}` };
};

const WEEKDAY_NAMES = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];

/** 0-6, "0".."6", "mon", "Monday", "tues" … → 0-6 (0 = Sunday); null when unknown. */
export const parseWeekday = (value) => {
    if (typeof value === "number") return Number.isInteger(value) && value >= 0 && value <= 6 ? value : null;
    const text = String(value ?? "").trim().toLowerCase();
    if (!text) return null;
    if (/^[0-6]$/.test(text)) return Number(text);
    if (text === "7") return 0;
    const index = WEEKDAY_NAMES.findIndex((name) => text.startsWith(name));
    return index === -1 ? null : index;
};

export const weekdayName = (day) => ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"][day] ?? String(day);

export const workHours = () => {
    const start = parseHHmm(process.env.WORK_DAY_START || "09:00");
    const end = parseHHmm(process.env.WORK_DAY_END || "17:00");
    // An invalid or inverted pair falls back to the documented default.
    if (!start || !end || end.minutes <= start.minutes) return { start: parseHHmm("09:00"), end: parseHHmm("17:00") };
    return { start, end };
};

export const workDays = () => {
    const raw = String(process.env.WORK_DAYS || "1,2,3,4,5,6");
    const days = [...new Set(raw.split(",").map((part) => parseWeekday(part)).filter((day) => day !== null))];
    return days.length ? days.sort((a, b) => a - b) : [1, 2, 3, 4, 5, 6];
};

let warnedAboutSecret = false;

const deviceSecret = () => {
    const configured = process.env.ATTENDANCE_DEVICE_SECRET;
    if (configured) return configured;
    if (!warnedAboutSecret && process.env.NODE_ENV !== "test") {
        warnedAboutSecret = true;
        console.warn("[attendance] ATTENDANCE_DEVICE_SECRET is not set; deriving the device-binding key from ACCESS_TOKEN_SECRET.");
    }
    return crypto.createHash("sha256").update(`attendance-device:${process.env.ACCESS_TOKEN_SECRET || ""}`).digest("hex");
};

/** HMAC-SHA256(deviceId) — the only form in which a device id is stored. */
export const hashDevice = (deviceId) => crypto.createHmac("sha256", deviceSecret()).update(String(deviceId)).digest("hex");
