// Course (`courses`): owned by a teacher, students enrol by join code, teacher
// list or auto-enrol; the weekly timetable drives session materialisation.
import mongoose, { Schema } from "mongoose";
import { COURSE_STATUSES, DEFAULT_SETTINGS, JOIN_CODE_RE, MAX_DURATION_MINUTES, MIN_DURATION_MINUTES } from "../config.js";

const { ObjectId } = Schema.Types;

const timetableSlotSchema = new Schema({
    day: { type: Number, required: true, min: 0, max: 6 },
    start: { type: String, required: true, match: /^([01]\d|2[0-3]):[0-5]\d$/ },
    durationMinutes: { type: Number, required: true, min: MIN_DURATION_MINUTES, max: MAX_DURATION_MINUTES, default: 60 },
    room: { type: String, trim: true, maxlength: 60 },
}, { _id: false });

const settingsSchema = new Schema({
    minAttendancePercent: { type: Number, min: 0, max: 100, default: DEFAULT_SETTINGS.minAttendancePercent },
    qrRotationSeconds: { type: Number, min: 5, max: 120, default: DEFAULT_SETTINGS.qrRotationSeconds },
    lateAfterMinutes: { type: Number, min: 0, max: 240, default: DEFAULT_SETTINGS.lateAfterMinutes },
    requireGeo: { type: Boolean, default: DEFAULT_SETTINGS.requireGeo },
    geoRadiusMeters: { type: Number, min: 10, max: 5000, default: DEFAULT_SETTINGS.geoRadiusMeters },
    autoEndGraceMinutes: { type: Number, min: 0, max: 240, default: DEFAULT_SETTINGS.autoEndGraceMinutes },
    autoGenerateDays: { type: Number, min: 1, max: 60, default: DEFAULT_SETTINGS.autoGenerateDays },
}, { _id: false });

const courseSchema = new Schema({
    code: { type: String, required: true, trim: true, uppercase: true, maxlength: 20 },
    name: { type: String, required: true, trim: true, maxlength: 160 },
    teacher: { type: ObjectId, ref: "User", required: true, index: true },
    department: { type: String, trim: true, maxlength: 80 },
    branch: { type: String, trim: true, maxlength: 80 },
    semester: { type: Number, min: 1, max: 12 },
    section: { type: String, trim: true, uppercase: true, maxlength: 10 },
    passingYear: { type: String, trim: true, maxlength: 10 },
    academicYear: { type: String, trim: true, maxlength: 20 },
    room: { type: String, trim: true, maxlength: 60 },
    students: { type: [{ type: ObjectId, ref: "User" }], default: [] },
    joinCode: { type: String, required: true, unique: true, match: JOIN_CODE_RE },
    timetable: {
        type: [timetableSlotSchema],
        default: [],
        validate: { validator: (slots) => slots.length <= 50, message: "A timetable can have at most 50 weekly slots" },
    },
    settings: { type: settingsSchema, default: () => ({}) },
    status: { type: String, enum: COURSE_STATUSES, default: "active", index: true },
}, { timestamps: true, collection: "courses" });

courseSchema.index({ students: 1 });
courseSchema.index(
    { teacher: 1, code: 1, section: 1, academicYear: 1 },
    { unique: true, partialFilterExpression: { status: "active" } },
);

export const Course = mongoose.models.Course || mongoose.model("Course", courseSchema);
