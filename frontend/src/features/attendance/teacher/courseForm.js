const HHMM = /^([01]?\d|2[0-3]):([0-5]\d)$/;
const text = (value) => (value === null || value === undefined ? "" : String(value));

export const emptyTimetableRow = () => ({ day: 1, start: "09:00", durationMinutes: "60", room: "" });

/** Form state for a new course or an existing one. */
export const courseToForm = (course = null) => ({
  code: text(course?.code),
  name: text(course?.name),
  department: text(course?.department),
  branch: text(course?.branch),
  semester: text(course?.semester),
  section: text(course?.section),
  passingYear: text(course?.passingYear),
  academicYear: text(course?.academicYear),
  room: text(course?.room),
  timetable: (course?.timetable || []).map((slot) => ({
    day: Number(slot.day),
    start: text(slot.start),
    durationMinutes: text(slot.durationMinutes ?? 60),
    room: text(slot.room),
  })),
  settings: Object.fromEntries(
    Object.entries({ ...DEFAULT_SETTINGS, ...(course?.settings || {}) })
      .filter(([key]) => key in DEFAULT_SETTINGS)
      .map(([key, value]) => [key, key === "requireGeo" ? Boolean(value) : text(value)]),
  ),
  autoEnroll: false,
});

const inRange = (value, [min, max]) => Number.isFinite(value) && value >= min && value <= max;

/** Validation errors keyed by field ("code", "timetable.0.start", "settings.qrRotationSeconds" …). */
export const validateCourseForm = (form) => {
  const errors = {};
  const code = form.code.trim();
  if (!code) errors.code = "Code is required, e.g. CS301";
  else if (!/^[A-Za-z0-9][A-Za-z0-9 _./-]{0,19}$/.test(code)) errors.code = "Up to 20 letters, digits, spaces or - _ . /";
  if (!form.name.trim()) errors.name = "Name is required";
  if (form.semester.trim()) {
    const semester = Number(form.semester);
    if (!Number.isInteger(semester) || semester < 1 || semester > 12) errors.semester = "Semester must be 1–12";
  }
  if (form.section.trim().length > 10) errors.section = "At most 10 characters";
  form.timetable.forEach((row, index) => {
    if (!HHMM.test(String(row.start).trim())) errors[`timetable.${index}.start`] = "Use HH:mm";
    const duration = Number(row.durationMinutes);
    if (!Number.isInteger(duration) || !inRange(duration, DURATION_BOUNDS)) {
      errors[`timetable.${index}.durationMinutes`] = `${DURATION_BOUNDS[0]}–${DURATION_BOUNDS[1]} min`;
    }
  });
  for (const [key, bounds] of Object.entries(SETTINGS_BOUNDS)) {
    const raw = form.settings[key];
    if (raw === "" || raw === null || raw === undefined) continue;
    if (!inRange(Number(raw), bounds)) errors[`settings.${key}`] = `Must be ${bounds[0]}–${bounds[1]}`;
  }
  if (form.autoEnroll && !form.branch.trim() && !form.department.trim()) {
    errors.branch = "Set the branch to auto-enroll students";
  }
  return errors;
};

export const timetableToPayload = (rows = []) =>
  rows.map((row) => {
    const slot = { day: Number(row.day), start: String(row.start).trim(), durationMinutes: Number(row.durationMinutes) };
    if (String(row.room ?? "").trim()) slot.room = String(row.room).trim();
    return slot;
  });

export const settingsToPayload = (settings = {}) => {
  const out = {};
  for (const key of Object.keys(SETTINGS_BOUNDS)) {
    const raw = settings[key];
    if (raw === "" || raw === null || raw === undefined) continue;
    out[key] = Number(raw);
  }
  out.requireGeo = Boolean(settings.requireGeo);
  return out;
};

const optional = (value) => {
  const trimmed = String(value ?? "").trim();
  return trimmed || null;
};

/** Form → POST /courses body (create) or PATCH body (update; empty optional fields are cleared with null). */
export const formToPayload = (form, { create = true } = {}) => {
  const body = {
    code: form.code.trim().toUpperCase(),
    name: form.name.trim(),
    department: optional(form.department),
    branch: optional(form.branch),
    semester: form.semester.trim() ? Number(form.semester) : null,
    section: optional(form.section)?.toUpperCase() ?? null,
    passingYear: optional(form.passingYear),
    academicYear: optional(form.academicYear),
    room: optional(form.room),
    timetable: timetableToPayload(form.timetable),
    settings: settingsToPayload(form.settings),
  };
  if (create) {
    for (const key of Object.keys(body)) if (body[key] === null) delete body[key];
    if (form.autoEnroll) body.autoEnroll = true;
  }
  return body;
};

/** Parse a pasted list of emails (commas, spaces, new lines, semicolons). */
export const parseEmailList = (value) => [
  ...new Set(
    String(value ?? "")
      .split(/[\s,;]+/)
      .map((email) => email.trim().toLowerCase())
      .filter(Boolean),
  ),
];
